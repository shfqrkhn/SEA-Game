// Verify the actual role-consumed engine, not only a standalone successor module.
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {runInNewContext} from 'node:vm';
const engine=readFileSync(new URL('../source/shared/engine.js',import.meta.url),'utf8');
const rules=runInNewContext(engine+'\n({parseAmount,parsePercentBps,profitFromBps,addCents,score,blank,makeBackup,parseBackup,createTeams,cardAt,acquire})');
// Input cannot invoke an arbitrary object's coercion hook at a domain boundary.
assert.throws(()=>rules.parseAmount({toString(){throw Error('executed-untrusted-coercion')}}),/money/);
assert.throws(()=>rules.score({mission:'COMBAT',totals:{...rules.blank(),MOB:Number.MAX_SAFE_INTEGER,FP:10}}),/capability/,'Unsafe scores must not enter award cross products');
assert.equal(rules.parseAmount('100,01'),10001);
assert.equal(rules.parsePercentBps('12.34'),1234n,'Existing controllers retain BigInt BPS signature');
assert.equal(rules.profitFromBps(199,2500n),50);
assert.equal(rules.score({mission:'COMMAND',totals:{CAP:11,COM:125}}),120);
assert.equal(rules.score({mission:null,totals:rules.blank()}),undefined,'Unassigned setup sentinel remains compatible');
const base={schema:3,sessionCode:'SEA3-T2-0123456789ABCDEF',phase:'planning',lang:'en'};
assert.throws(()=>rules.makeBackup('STUDENT',{...base,marketSeed:'PRIVATE-SEED'}),/invalid-state/,'Student export cannot contain instructor-only data even before the role validator');
const mislabeled={format:'SEA-GAME-BACKUP',version:1,appVersion:'3.0.0',ruleset:'STANDARD',deck:'synthetic-v1',schema:3,sessionCode:base.sessionCode,role:'STUDENT',state:{...base,ledger:[]}};
let validatorCalled=false;
assert.throws(()=>rules.parseBackup(JSON.stringify(mislabeled),'STUDENT',x=>{validatorCalled=true;return x}),/invalid-state/,'Mislabeled role data is rejected before invoking the role validator');
assert.equal(validatorCalled,false);
const live=rules.createTeams({teamCount:2})[0];live.mission='COMBAT';
rules.acquire(live,rules.cardAt('CAP-A',1,1),30000000);
let hooks=0;
live.purchases[0].e={CAP:6,MOB:-10,toJSON(){hooks++;throw Error('metadata serializer executed')}};
Object.setPrototypeOf(live.purchases,Object.create(Array.prototype,{map:{value(){hooks++;throw Error('array map hook executed')}}}));
rules.acquire(live,rules.cardAt('MOB-A',1,2),40000000);
assert.equal(hooks,0,'Adapter comparison cannot execute untrusted metadata or array-prototype hooks');
assert.equal(live.cost,70000000);assert.equal(live.totals.CAP,6);assert.equal(live.totals.MOB,60);
assert.doesNotThrow(()=>JSON.stringify(live),'Only canonical inert metadata survives a successful commit');
assert.match(engine,/BEGIN TYPED DOMAIN/,'The role engine consumes built typed source');
console.log('Actual engine typed money/score and role backup boundaries, independent cent/score cases and setup compatibility PASS');
