import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const code=fs.readFileSync(new URL('../source/shared/three-presentation.js',import.meta.url),'utf8');
const ctx=vm.createContext({});vm.runInContext(code+'\nthis.project=seaSceneProjection;',ctx);
const text=value=>({nodeType:3,textContent:value});
function node(tag,content='',children=[],props={}){
 const n={tagName:tag.toUpperCase(),nodeType:1,childNodes:[...(content?[text(content)]:[]),...children],children,labels:[],disabled:false,hidden:false,...props};
 n.classList={contains:c=>(n.classes||[]).includes(c)};
 n.getAttribute=k=>n.attrs?.[k]||null;n.closest=()=>null;
 n.querySelector=selector=>n.querySelectorAll(selector)[0]||null;
 n.querySelectorAll=selector=>{const tags=selector.split(',');return children.flatMap(c=>[...(tags.includes(c.tagName?.toLowerCase())?[c]:[]),...(c.querySelectorAll?.(selector)||[])]);};
 Object.defineProperty(n,'textContent',{get:()=>n.childNodes.map(c=>c.textContent||'').join(' ')});return n;
}
const secret='UNREVEALED_PRIVATE_MARKET';
const label=node('label','Session code'),input=node('input','',[],{value:'SEA3-T2-1234567890ABCDEF',labels:[label]});
const disabled=node('button','Advance',[],{disabled:true});
const hidden=node('p',secret,[],{hidden:true});
const mixed=node('p','Public result',[hidden]);
const row=node('tr','Team 1',[node('td',secret,[],{hidden:true}),node('button','Remove')]);
const closed=node('details','',[node('summary','Save'),node('button','Export')],{open:false});
const effects=node('div','Capacity',[node('strong','+4'),node('small','persons')],{classes:['effect']});
const purchase=node('div','',[node('span','R1 / L2'),node('span','MOB-A'),node('strong','$350,000'),node('button','Remove purchase')]);
const root=node('section','',[input,disabled,hidden,mixed,row,closed,node('strong','$250,000'),node('span','CAP-A'),effects,purchase]);
let id=0;const keys=new WeakMap();const keyFor=n=>{if(!keys.has(n))keys.set(n,String(++id));return keys.get(n);};
const visible=n=>!n.hidden;
const before=input.value,projection=ctx.project([root,root],visible,keyFor);
assert(!JSON.stringify(projection.rows).includes(secret),'Hidden DOM content must never enter GPU text');
assert.equal(projection.rows.filter(r=>r.label==='Session code').length,1,'Repeated roots cannot duplicate controls');
assert.equal(projection.rows.find(r=>r.label==='Session code').value,before);
assert.equal(projection.rows.find(r=>r.label==='Advance').disabled,true);
assert(!projection.rows.some(r=>r.label==='Export'),'Closed details content is not displayed');
assert(projection.rows.some(r=>r.label==='Remove'),'Table actions remain actionable');
assert.equal(input.value,before,'Projection cannot mutate native inputs');
for(const value of ['$250,000','CAP-A','Capacity +4 persons','R1 / L2','MOB-A','$350,000'])assert(projection.rows.some(r=>r.label===value),'Production price/effect/purchase text omitted: '+value);
const ranking=node('div','',[node('strong','1. Team 1'),node('div','$4,000,000 · 80 points · $50,000.00')],{classes:['inv']});
const prompts=node('ol','',[node('li','Explain the cost tradeoff.'),node('li','Identify the mission shortfall.')]);
const info=ctx.project([ranking,prompts],visible,keyFor).rows.map(r=>r.label);
for(const value of ['1. Team 1','$4,000,000 · 80 points · $50,000.00','Explain the cost tradeoff.','Identify the mission shortfall.'])assert(info.includes(value),'Ranking/debrief information must survive: '+value);
const inlineLabel=node('label','Profit',[node('span',secret,[],{hidden:true})]);
const privateLabelInput=node('input','',[],{value:'250000',labels:[inlineLabel]});
assert(!JSON.stringify(ctx.project([privateLabelInput],visible,keyFor).rows).includes(secret),'Hidden label descendants must not enter GPU control names');
closed.open=true;assert(ctx.project([root],visible,keyFor).rows.some(r=>r.label==='Export'));
hidden.hidden=false;assert(JSON.stringify(ctx.project([root],visible,keyFor).rows).includes(secret),'Visible content must not be accidentally omitted');
console.log('Scene projection hidden-content privacy, identity, disabled controls, summaries, table actions and immutability PASS');
